// Rebuilds lib/brochure-html.ts from content/brochures/*.html, the four faces of
// the two trifolds (wedding and corporate, outside and inside). Each file is the
// face's markup at print size, 1056x816 CSS px (letter landscape), with inline
// styles only, so the same markup renders on screen (scaled) and prints 1:1.
// The master copy of the design is the "Crossroads Trifold Brochures" canvas on
// claude.ai; when it changes, re-export the faces here and run:
//   node scripts/build-brochures.mjs
import { readFileSync, writeFileSync } from "node:fs";

const face = (name) =>
  readFileSync(new URL(`../content/brochures/${name}.html`, import.meta.url), "utf8").trim();

const faces = {
  wedding: { outside: face("wedding-outside"), inside: face("wedding-inside") },
  corporate: { outside: face("corporate-outside"), inside: face("corporate-inside") },
};

for (const [kind, sides] of Object.entries(faces)) {
  for (const [side, html] of Object.entries(sides)) {
    if (html.includes("—")) throw new Error(`${kind}-${side}: em dash (house rule: none, anywhere)`);
    if (/<script/i.test(html)) throw new Error(`${kind}-${side}: faces are static markup, no scripts`);
  }
}

const out =
  "// GENERATED by scripts/build-brochures.mjs from content/brochures/*.html. Do not edit.\n" +
  `export const BROCHURE_FACES = ${JSON.stringify(faces, null, 2)} as const;\n`;
writeFileSync(new URL("../lib/brochure-html.ts", import.meta.url), out);
console.log(`lib/brochure-html.ts written (${out.length} chars)`);
